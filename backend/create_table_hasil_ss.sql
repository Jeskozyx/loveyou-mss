-- 1. BUAT TABEL hasil_ss
CREATE TABLE IF NOT EXISTS public.hasil_ss (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    filename TEXT NOT NULL,
    image_url TEXT,
    storage_path TEXT,
    device_name TEXT,
    resolution TEXT,
    active_window TEXT,
    file_size_kb NUMERIC(10, 2),
    status TEXT DEFAULT 'success',
    notes TEXT
);

-- 2. TAMBAHKAN INDEX UNTUK PERFORMA QUERY
CREATE INDEX IF NOT EXISTS idx_hasil_ss_created_at ON public.hasil_ss(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_hasil_ss_device_name ON public.hasil_ss(device_name);

-- 3. BERIKAN HAK AKSES TABEL KE ROLE anon, authenticated, service_role
GRANT ALL ON TABLE public.hasil_ss TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 4. AKTIFKAN ROW LEVEL SECURITY (RLS)
ALTER TABLE public.hasil_ss ENABLE ROW LEVEL SECURITY;

-- 5. BUAT POLICY AGAR API KEY (anon / publishable key) BISA INSERT & SELECT
DROP POLICY IF EXISTS "Allow public insert into hasil_ss" ON public.hasil_ss;
CREATE POLICY "Allow public insert into hasil_ss"
ON public.hasil_ss
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read from hasil_ss" ON public.hasil_ss;
CREATE POLICY "Allow public read from hasil_ss"
ON public.hasil_ss
FOR SELECT
TO anon, authenticated
USING (true);

-- 6. BUAT STORAGE BUCKET 'screenshots' (Jika belum ada)
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'screenshots',
    'screenshots',
    true,
    10485760, -- Limit 10MB per gambar
    ARRAY['image/png', 'image/jpeg']
)
ON CONFLICT (id) DO UPDATE 
SET public = true;

-- 7. POLICY UNTUK STORAGE BUCKET 'screenshots'
-- Memungkinkan upload file via anon / publishable key
DROP POLICY IF EXISTS "Allow anon upload to screenshots" ON storage.objects;
CREATE POLICY "Allow anon upload to screenshots"
ON storage.objects
FOR INSERT
TO anon, authenticated
WITH CHECK (bucket_id = 'screenshots');

-- Memungkinkan melihat file screenshot secara publik
DROP POLICY IF EXISTS "Allow anon view screenshots" ON storage.objects;
CREATE POLICY "Allow anon view screenshots"
ON storage.objects
FOR SELECT
TO anon, authenticated
USING (bucket_id = 'screenshots');
